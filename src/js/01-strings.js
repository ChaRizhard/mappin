  function detectLanguage() {
    try {
      const saved = localStorage.getItem('mappin_lang');
      if (saved && I18N[saved]) return saved;
    } catch (e) {}
    const nav = (navigator.language || 'en').slice(0, 2).toLowerCase();
    return I18N[nav] ? nav : 'en';
  }

  let LANG = detectLanguage();

  function t(key, vars) {
    // Singular forms ("1 day", "1 stop") where a language has them
    if (vars && Number(vars.n) === 1) {
      const L = I18N[LANG] || {};
      if (L[key + '_one'] || (!L[key] && I18N.en[key + '_one'])) key = key + '_one';
    }
    let s = (I18N[LANG] && I18N[LANG][key]) || I18N.en[key] || key;
    if (vars) Object.keys(vars).forEach(k => { s = s.split(`{${k}}`).join(vars[k]); });
    return s;
  }

  function applyI18n() {
    document.documentElement.lang = LANG;
    document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.getAttribute('data-i18n')); });
    document.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = t(el.getAttribute('data-i18n-ph')); });
    document.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.getAttribute('data-i18n-title')); });
    if (typeof labelIconButtons === 'function') labelIconButtons();
    const sel = document.getElementById('lang-select');
    if (sel && !sel.options.length) {
      LANGUAGES.forEach(l => { const o = document.createElement('option'); o.value = l.code; o.textContent = l.name; sel.appendChild(o); });
    }
    if (sel) sel.value = LANG;
  }
